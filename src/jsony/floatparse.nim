proc bitsF64(negative: bool, exp: int, mant: uint64): float64 {.inline.} =
  var bits = (if negative: 1'u64 shl 63 else: 0'u64) or (uint64(exp) shl 52) or (mant and 0x000f_ffff_ffff_ffff'u64)
  result = cast[float64](bits)

proc eiselCompute*(w: uint64, q: int, negative: bool, outv: var float64): bool =
  ## Try Eisel-Lemire for w*10^q. Returns false on any ambiguity => fallback.
  if w == 0'u64:
    outv = if negative: -0.0 else: 0.0
    return true
  if q < eiselSmallest or q > eiselLargest:
    return false

  let idx = q - eiselSmallest
  let am = eiselPowers[idx]
  let ae = int(eiselExps[idx])

  # 192-bit product P = w * am
  let p1 = mul64(w, am[0]) # w*hi
  let p2 = mul64(w, am[1]) # w*lo
  let middleSum = p1.lo + p2.hi
  let carry = if middleSum < p1.lo: 1'u64 else: 0'u64
  let upper = p1.hi + carry
  let middle = middleSum
  let lower = p2.lo

  # leading zeros of 128-bit (upper,middle)
  var lz: int
  if upper != 0'u64:
    lz = countLeadingZeroBits(upper)
  elif middle != 0'u64:
    lz = 64 + countLeadingZeroBits(middle)
  else:
    return false

  # 10^q = (am / 2^127) * 2^ae  => w*10^q = (w*am / 2^127) * 2^ae
  # w*am highest bit at 191-lz => value ~ 2^(191-lz - 127 + ae) = 2^(ae + 64 - lz)
  let e2 = ae + 64 - lz

  # normalize to 128-bit window hiw:loww with hiw MSB set
  var hiw, loww, dropped: uint64
  if upper != 0'u64:
    let s = lz
    if s == 0:
      hiw = upper; loww = middle; dropped = lower
    else:
      hiw = (upper shl s) or (middle shr (64 - s))
      loww = (middle shl s) or (lower shr (64 - s))
      dropped = lower shl s
  else:
    let s = lz - 64
    if s == 0:
      hiw = middle; loww = lower; dropped = 0
    else:
      hiw = (middle shl s) or (lower shr (64 - s))
      loww = lower shl s
      dropped = 0

  # IEEE mantissa: 53 bits (implicit 1 at bit 52). Round using bit 10 and rest.
  let mant53 = hiw shr 11            # bits 63..11 -> 53 bits
  let roundBit = (hiw shr 10) and 1'u64
  let tail10 = hiw and ((1'u64 shl 10) - 1'u64)
  let sticky = (if tail10 != 0'u64 or loww != 0'u64 or dropped != 0'u64: 1'u64 else: 0'u64)

  # Conservative: reject exact halfway (safety against table approximation edge cases)
  if roundBit == 1'u64 and sticky == 0'u64:
    return false

  var mant = mant53
  var exp2 = e2
  if roundBit == 1'u64 and sticky == 1'u64:
    mant += 1'u64
    if mant == (1'u64 shl 53):
      mant = mant shr 1        # 1.0 * 2^(exp2+1)
      exp2 += 1

  if mant >= (1'u64 shl 53):
    mant = mant shr 1
    exp2 += 1
  if mant < (1'u64 shl 52):
    return false

  let ieeeExp = exp2 + 1023
  # Conservative: avoid subnormals and overflow; let original handle them
  if ieeeExp <= 0 or ieeeExp >= 2047:
    return false

  let frac = mant and ((1'u64 shl 52) - 1'u64)
  outv = bitsF64(negative, ieeeExp, frac)
  return true
