## Eisel-Lemire fast decimal-to-float64 (conservative, strict fallback).
## Returns false on ambiguity/out-of-range/subnormal-edge so caller uses
## parseutils.parseFloat for exact compatibility.

import std/bitops

type Uint128 = object
  hi: uint64
  lo: uint64

proc mul64(a, b: uint64): Uint128 {.inline.} =
  let
    al = a and 0xffff_ffff'u64
    ah = a shr 32
    bl = b and 0xffff_ffff'u64
    bh = b shr 32
    p0 = al * bl
    p1 = al * bh
    p2 = ah * bl
    p3 = ah * bh
    mid = (p0 shr 32) + (p1 and 0xffff_ffff'u64) + (p2 and 0xffff_ffff'u64)
  result.lo = (p0 and 0xffff_ffff'u64) or (mid shl 32)
  result.hi = p3 + (p1 shr 32) + (p2 shr 32) + (mid shr 32)

